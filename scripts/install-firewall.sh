#!/bin/sh
# Installs petri.'s firewall on this host (run as root):
#
#   sudo scripts/install-firewall.sh [options]   install or update, and apply
#   sudo scripts/install-firewall.sh --remove    remove it again
#
# Always: egress filtering for apps and builds (infrastructure/firewall/
# petri.nft). On the production host, also who may reach it:
#
#   --npm ADDRESS     only this address (the NPM VM) may reach the published
#                     ports; everyone else is dropped
#   --ports LIST      those ports, comma-separated (default: 3000,8080, the
#                     defaults of WEB_PORT and EDGE_PORT)
#   --ssh-from CIDR   SSH only from this network (e.g. 192.168.0.0/24).
#                     Refused if your current SSH session isn't in it.
#   --dry-run         print the access rules and check both files; change
#                     nothing
#
# Without --npm and --ssh-from, existing access rules are kept, so an
# update (after `git pull`) needs no options.
#
# Then check it with scripts/probe-egress.sh. Needs nftables
# (Debian/Ubuntu: apt install nftables) and systemd.
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
unit=/etc/systemd/system/petri-firewall.service
npm=""
ports="3000,8080"
ssh_from=""
remove=""
dry_run=""

while [ $# -gt 0 ]; do
	case "$1" in
	--remove) remove=1 ;;
	--dry-run) dry_run=1 ;;
	--npm) npm=$2; shift ;;
	--ports) ports=$2; shift ;;
	--ssh-from) ssh_from=$2; shift ;;
	*) echo "Unknown option: $1" >&2; exit 2 ;;
	esac
	shift
done

if [ "$(id -u)" != 0 ] && [ -z "$dry_run" ]; then
	echo "Run as root (sudo $0)." >&2
	exit 1
fi

if [ -n "$remove" ]; then
	# Docker requires the firewall, so stopping it stops Docker first:
	# nothing runs unfiltered in between. Start Docker again afterwards.
	systemctl disable --now petri-firewall.service 2>/dev/null || true
	rm -f "$unit" /etc/petri/petri.nft /etc/petri/access.nft
	rmdir /etc/petri 2>/dev/null || true
	systemctl daemon-reload
	systemctl start docker.service
	echo "Removed. Apps and builds can reach the LAN again."
	exit 0
fi

if [ ! -x /usr/sbin/nft ]; then
	echo "nftables is missing: apt install nftables" >&2
	exit 1
fi

ipv4='^([0-9]{1,3}\.){3}[0-9]{1,3}$'
cidr4='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
if [ -n "$npm" ] && ! echo "$npm" | grep -Eq "$ipv4"; then
	echo "--npm needs an IPv4 address, got: $npm" >&2
	exit 2
fi
if ! echo "$ports" | grep -Eq '^[0-9]{1,5}(,[0-9]{1,5})*$'; then
	echo "--ports needs comma-separated port numbers, got: $ports" >&2
	exit 2
fi
if [ -n "$ssh_from" ]; then
	if ! echo "$ssh_from" | grep -Eq "$cidr4"; then
		echo "--ssh-from needs an IPv4 network (a.b.c.d/n), got: $ssh_from" >&2
		exit 2
	fi
fi

# True if IPv4 address $1 is in network $2 (a.b.c.d/n).
in_network() {
	echo "$1 $2" | awk '{
		split($1, a, "."); split($2, n, "[./]")
		ip = ((a[1] * 256 + a[2]) * 256 + a[3]) * 256 + a[4]
		net = ((n[1] * 256 + n[2]) * 256 + n[3]) * 256 + n[4]
		size = 2 ^ (32 - n[5])
		exit !(int(ip / size) == int(net / size))
	}'
}
# Don't lock out the session running this.
if [ -n "$ssh_from" ] && [ -n "${SSH_CONNECTION:-}" ]; then
	client=${SSH_CONNECTION%% *}
	if ! in_network "$client" "$ssh_from"; then
		echo "Your SSH session comes from $client, outside $ssh_from: refusing to lock you out." >&2
		exit 1
	fi
fi

# Who may reach this host: written from the options, kept next to the
# egress rules. A table of its own, like those.
access=$(mktemp)
trap 'rm -f "$access"' EXIT
if [ -z "$npm" ] && [ -z "$ssh_from" ] && [ -e /etc/petri/access.nft ]; then
	echo "Keeping the access rules in /etc/petri/access.nft."
	cp /etc/petri/access.nft "$access"
else
{
	echo "# Generated by scripts/install-firewall.sh; rerun it to change."
	echo "table inet petri_access"
	echo "delete table inet petri_access"
	echo "table inet petri_access {"
	if [ -n "$npm" ]; then
		cat <<EOF
	chain prerouting {
		# Before Docker forwards published ports to containers (dstnat), so
		# this sees them; they never pass the input chain. Loopback is
		# exempt: the host itself may use them.
		type filter hook prerouting priority mangle; policy accept;
		iifname != "lo" fib daddr type local tcp dport { $ports } ip saddr != $npm counter drop
		iifname != "lo" fib daddr type local tcp dport { $ports } meta nfproto ipv6 counter drop
	}
EOF
	fi
	if [ -n "$ssh_from" ]; then
		cat <<EOF
	chain input {
		type filter hook input priority filter - 10; policy accept;
		tcp dport 22 ip saddr != $ssh_from counter drop
		tcp dport 22 meta nfproto ipv6 counter drop
	}
EOF
	fi
	echo "}"
} >"$access"
fi

if [ -n "$dry_run" ]; then
	cat "$access"
	# Checking needs root too; without it, only the text above.
	if [ "$(id -u)" = 0 ]; then
		nft -c -f "$here/infrastructure/firewall/petri.nft"
		nft -c -f "$access"
		echo "# Both files are valid."
	fi
	exit 0
fi

# Refuse broken files before replacing working ones.
nft -c -f "$here/infrastructure/firewall/petri.nft"
nft -c -f "$access"

install -D -m 0644 "$here/infrastructure/firewall/petri.nft" /etc/petri/petri.nft
install -m 0644 "$access" /etc/petri/access.nft
install -m 0644 "$here/infrastructure/firewall/petri-firewall.service" "$unit"
systemctl daemon-reload
systemctl enable petri-firewall.service
# Reloading swaps the rules in one step; never a moment without them.
systemctl reload-or-restart petri-firewall.service
nft list table inet petri >/dev/null
echo "Installed and active."
[ -n "$npm" ] && echo "  Ports $ports: only from $npm."
[ -n "$ssh_from" ] && echo "  SSH: only from $ssh_from."
echo "Check it with: scripts/probe-egress.sh"
